"""Write scene-data.js for the live-mode game mockups from R004_SCENE_GEOMETRY_2D_V1.json.

Display-only (minimap base map); not runtime inference input. Usage (repo root):
    python3 docs/design/img/live-mode-game-v1/make_scene_data.py
"""
import json, math, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[4]
g = json.loads((ROOT / "docs/evaluation/R004_SCENE_GEOMETRY_2D_V1.json").read_text())
cams = []
for c in g["cameras"]:
    M = c["camera_to_world"]
    fwd = [-M[0][2], -M[1][2], -M[2][2]]
    cams.append({
        "id": c["camera_id"], "x": round(M[0][3], 3), "y": round(M[1][3], 3), "z": round(M[2][3], 3),
        "yaw_deg": round(math.degrees(math.atan2(fwd[1], fwd[0])), 2),
        "hfov_deg": round(2 * math.degrees(math.atan(c["cx"] / c["fx"])), 2),
    })
out = {
    "source": "docs/evaluation/R004_SCENE_GEOMETRY_2D_V1.json",
    "floors": [{"x": f["x_m"], "y": f["y_m"]} for f in g["floors"]],
    "walls": [[round(v, 3) for v in (*s["a"], *s["b"])] for s in g["clearance_segments"]
              if not s["collider"].startswith("R004_ENV_")],
    "vehicle": [[round(v, 3) for v in (*s["a"], *s["b"])] for s in g["clearance_segments"]
                if s["collider"].startswith("R004_ENV_")],
    "cameras": cams,
}
p = pathlib.Path(__file__).with_name("scene-data.js")
p.write_text("// generated by make_scene_data.py — display only\nwindow.SCENE = " + json.dumps(out, separators=(",", ":")) + ";\n")
print(p, len(out["walls"]), "walls", len(cams), "cams")
